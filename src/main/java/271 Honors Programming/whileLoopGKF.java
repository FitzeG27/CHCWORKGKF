public class whileLoopGKF {
    public static void main(String[] args) {
        
        int i = 0;
        while(i<10000000){
            i++;
            System.out.print(i);
        }
    }
}
/*1. Int i = 1 (Initialize loop control variable)
 *2. While (i<=10) (Boundary condition)
 *3. i++ (modify LCV) */